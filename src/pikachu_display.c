// Draw raw bitmap to display
static void draw_bitmap(const uint8_t *bitmap, int width_bytes, int height) {
    if (display_dev == NULL) {
        return;
    }

#ifdef CONFIG_DISPLAY_FRAMEBUFFER
    if (cfb_framebuffer_clear(display_dev, true) != 0) {
        return;
    }

    // Center the Pikachu horizontally (128 - 56 = 72, so start at x=36)
    int x_offset = 36;
    int y_offset = 2;

    for (int y = 0; y < height; y++) {
        for (int x = 0; x < width_bytes; x++) {
            uint8_t byte = bitmap[y * width_bytes + x];

            // Draw each bit as a pixel
            for (int bit = 0; bit < 8; bit++) {
                if (byte & (0x80 >> bit)) {
                    cfb_framebuffer_set(display_dev,
                                      x_offset + x * 8 + bit,
                                      y_offset + y,
                                      1);
                }
            }
        }
    }

    cfb_framebuffer_finalize(display_dev);
#endif
}

static void pikachu_animation_timer(struct k_timer *timer_id) {
    uint8_t frame_num = (animation_frame++ / 4) % 3;

    switch (frame_num) {
        case 0:
            draw_bitmap(pikachu_frame0, 7, 28);
            break;
        case 1:
            draw_bitmap(pikachu_frame1, 7, 28);
            break;
        case 2:
            draw_bitmap(pikachu_frame2, 7, 28);
            break;
    }
}

K_TIMER_DEFINE(pikachu_timer, pikachu_animation_timer, NULL);

static int pikachu_display_init(void) {
    display_dev = DEVICE_DT_GET(DT_CHOSEN(zephyr_display));

    if (display_dev == NULL || !device_is_ready(display_dev)) {
        LOG_WRN("Display device not available");
        return -ENODEV;
    }

    LOG_INF("🐤 Pikachu pixel-art display initialized!");

    // Start animation (update every 300ms)
    k_timer_start(&pikachu_timer, K_MSEC(300), K_MSEC(300));

    return 0;
}

SYS_INIT(pikachu_display_init, POST_KERNEL, CONFIG_KERNEL_INIT_PRIORITY_DEFAULT);
